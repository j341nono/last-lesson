// Each arc has four distinct nodes. Explicit edges describe causal continuations.
export const events: Event[] = arcs.flatMap((arc) =>
  arc.rows.map((r, i) => ({
    id: `${arc.id}-${i}`,
    arc: arc.id,
    gate: gates[`${arc.id}-${i}`],
    stage: i,
    title: r[0],
    text: r[1],
    requires: r[2] || undefined,
    region: arc.region,
    scene: arc.scene,
    weight: i === 0 ? 1 : 3,
    critical: i > 0 || arc.id === "war",
    years: 1.1,
    actions: r[3],
    next: arc.rows.flatMap((v, j) =>
      j > i && v[2] && r[3].some((a) => a.memory === v[2])
        ? [`${arc.id}-${j}`]
        : [],
    ),
  })),
);
export const eventMap = Object.fromEntries(events.map((e) => [e.id, e]));
